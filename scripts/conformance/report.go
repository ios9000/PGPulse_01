package main

import (
	"fmt"
	"regexp"
	"sort"
	"strings"
)

// Summary counts collector outcomes across all servers.
type Summary struct {
	OK, Warn, Fail, Unreachable int
}

// Summarize counts outcomes in a report.
func Summarize(rep Report) Summary {
	var s Summary
	for _, srv := range rep.Servers {
		if srv.ConnectError != "" {
			s.Unreachable++
			continue
		}
		for _, c := range srv.Collectors {
			switch c.Status {
			case StatusOK:
				s.OK++
			case StatusWarn:
				s.Warn++
			default:
				s.Fail++
			}
		}
	}
	return s
}

func rowKey(c CollectorResult) string {
	if c.Path == "standby" {
		return c.Name + " (standby path)"
	}
	return c.Name
}

func failedCount(c CollectorResult) int {
	n := 0
	for _, s := range c.Statements {
		if s.Error != "" {
			n++
		}
	}
	return n
}

func cell(c CollectorResult) string {
	n := len(c.Statements)
	switch {
	case c.Status == StatusOK && n == 0:
		return "➖ no SQL"
	case c.Status == StatusOK:
		return fmt.Sprintf("✅ ok (%d)", n)
	case c.Status == StatusWarn:
		return fmt.Sprintf("⚠️ warn (%d/%d)", failedCount(c), n)
	default:
		return "❌ fail"
	}
}

func truncate(s string, n int) string {
	if len(s) <= n {
		return s
	}
	return s[:n] + "…"
}

func mdEscape(s string) string {
	return strings.ReplaceAll(s, "|", `\|`)
}

var sqlstateRe = regexp.MustCompile(`SQLSTATE ([0-9A-Z]{5})`)

// category classifies a statement error by SQLSTATE so privilege problems
// (pg_monitor is not enough) are not confused with version/catalog drift.
func category(errText string) string {
	m := sqlstateRe.FindStringSubmatch(errText)
	if m == nil {
		return "other"
	}
	switch m[1] {
	case "42501":
		return "privilege"
	case "42703", "42P01", "42883", "42704":
		return "catalog / version"
	default:
		return "SQLSTATE " + m[1]
	}
}

// expectedVersion is major.minor derived from server_version_num the way
// PostgreSQL ≥ 10 defines it (MMmmmm → MM.mmmm).
func expectedVersion(num int) string {
	return fmt.Sprintf("%d.%d", num/10000, num%10000)
}

type failureGroup struct {
	collector string
	sql       string
	errText   string
	args      map[string]bool
	labels    []string
}

// RenderMarkdown renders the collector × version matrix and failure list.
func RenderMarkdown(rep Report) string {
	var b strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&b, format, a...) }

	w("# PostgreSQL version conformance\n\n")
	w("> Generated by `scripts/conformance/run.sh` — do not edit by hand.  \n")
	w("> Generated: %s", rep.GeneratedAt.Format("2006-01-02 15:04 UTC"))
	if rep.Commit != "" {
		w(" · Commit: `%s`", rep.Commit)
	}
	w("  \n> Provisioning route: %s\n\n", rep.Route)

	w("Every collector is constructed exactly as `orchestrator.buildCollectors` does, handed the\n")
	w("`version.PGVersion` returned by `version.Detect` for that server, and run once with `Collect`\n")
	w("(per-database collector: `CollectDB` against a seeded `conformance` database;\n")
	w("`statements_snapshot` is `statements.SnapshotCapturer.CaptureInstance`, the other `version.Gate` user).\n")
	w("A pgx query tracer records every statement the collector issues, so the SQL executed is the variant\n")
	w("the collector's own gating selected — the harness does not re-implement selection.\n")
	w("The connection role is `pgpulse_monitor`, granted `pg_monitor` only (never superuser).\n\n")
	w("Legend: ✅ ok (N) — Collect succeeded and all N statements succeeded · ➖ no SQL — the collector\n")
	w("issues no SQL on this version (version check skipped it) · ⚠️ warn (E/N) — Collect returned no\n")
	w("error but E of N statements failed and the collector swallowed the error · ❌ fail — Collect\n")
	w("returned an error. *standby path* rows re-run the collector with `IsRecovery=true` against the\n")
	w("primary so its replica-only SQL is executed too.\n\n")
	w("Re-generate: `scripts/conformance/run.sh` (see `scripts/conformance/README.md`).\n\n")

	// Servers table.
	w("## Servers\n\n")
	w("| Label | server_version | server_version_num | `version.Detect` → `PGVersion.String()` | Executed |\n")
	w("|---|---|---|---|---|\n")
	minorMismatch := false
	for _, s := range rep.Servers {
		exec := "yes"
		if s.ConnectError != "" {
			exec = "**NO** — " + mdEscape(s.ConnectError)
		}
		det := s.Detected
		if s.ConnectError == "" && det != expectedVersion(s.ServerVersionNum) {
			det += fmt.Sprintf(" (expected %s)", expectedVersion(s.ServerVersionNum))
			minorMismatch = true
		}
		w("| %s | %s | %d | %s | %s |\n", s.Label, mdEscape(s.ServerVersion), s.ServerVersionNum, det, exec)
	}
	w("\n")
	if minorMismatch {
		w("**Note:** `version.Detect` computes `Minor` as `num %% 10000 / 100`, the pre-10 encoding\n")
		w("(`MMmmpp`). For PostgreSQL ≥ 10 `server_version_num` is `MMmmmm`, so `Minor` is always 0.\n")
		w("No current gate depends on the minor version (all ranges use `MinMinor: 0` / `MaxMinor: 99`),\n")
		w("so SQL selection is unaffected today. Current behaviour is pinned by `TestDetectLive` in `internal/version`.\n\n")
	}

	// Matrix.
	var order []string
	seen := map[string]bool{}
	cells := map[string]map[string]string{}
	for _, s := range rep.Servers {
		for _, c := range s.Collectors {
			k := rowKey(c)
			if !seen[k] {
				seen[k] = true
				order = append(order, k)
			}
			if cells[k] == nil {
				cells[k] = map[string]string{}
			}
			cells[k][s.Label] = cell(c)
		}
	}
	sort.Strings(order)

	w("## Matrix\n\n| Collector |")
	for _, s := range rep.Servers {
		w(" %s |", s.Label)
	}
	w("\n|---|")
	for range rep.Servers {
		w("---|")
	}
	w("\n")
	for _, k := range order {
		w("| `%s` |", k)
		for _, s := range rep.Servers {
			v, ok := cells[k][s.Label]
			if !ok {
				v = "not executed"
			}
			w(" %s |", v)
		}
		w("\n")
	}
	sum := Summarize(rep)
	w("\nTotals: %d ok · %d warn · %d fail · %d server(s) not executed.\n\n", sum.OK, sum.Warn, sum.Fail, sum.Unreachable)

	// Failures, grouped by (collector, statement, error) across servers.
	var groups []*failureGroup
	gidx := map[string]*failureGroup{}
	for _, s := range rep.Servers {
		for _, c := range s.Collectors {
			if c.Status == StatusOK {
				continue
			}
			add := func(sql, errText string, args []string) {
				key := rowKey(c) + "\x00" + sql + "\x00" + errText
				g, ok := gidx[key]
				if !ok {
					g = &failureGroup{collector: rowKey(c), sql: sql, errText: errText, args: map[string]bool{}}
					gidx[key] = g
					groups = append(groups, g)
				}
				if len(g.labels) == 0 || g.labels[len(g.labels)-1] != s.Label {
					g.labels = append(g.labels, s.Label)
				}
				if len(args) > 0 {
					g.args[strings.Join(args, ", ")] = true
				}
			}
			n := 0
			for _, st := range c.Statements {
				if st.Error != "" {
					add(st.SQL, st.Error, st.Args)
					n++
				}
			}
			if n == 0 && c.Error != "" {
				add("", c.Error, nil) // failure not tied to a traced statement
			}
		}
	}
	sort.SliceStable(groups, func(i, j int) bool {
		ci, cj := category(groups[i].errText), category(groups[j].errText)
		if ci != cj {
			return ci < cj
		}
		return groups[i].collector < groups[j].collector
	})

	w("## Failures\n\n")
	if len(groups) == 0 {
		w("None.\n\n")
	} else {
		w("Distinct failing statements. *Category* is derived from SQLSTATE: `catalog / version` = the\n")
		w("selected SQL references a column/relation/function that does not exist on that version;\n")
		w("`privilege` = the statement needs more than `pg_monitor`.\n\n")
		w("| # | Collector | Category | Versions | Error |\n|---|---|---|---|---|\n")
		for i, g := range groups {
			w("| F%d | `%s` | %s | %s | `%s` |\n", i+1, g.collector, category(g.errText),
				strings.Join(g.labels, ", "), mdEscape(g.errText))
		}
		w("\n")
		for i, g := range groups {
			w("### F%d · `%s` · %s\n\n", i+1, g.collector, strings.Join(g.labels, ", "))
			if g.sql != "" {
				w("```sql\n%s\n```\n\n", truncate(g.sql, 1200))
			}
			if len(g.args) > 0 {
				var as []string
				for a := range g.args {
					as = append(as, "`"+a+"`")
				}
				sort.Strings(as)
				w("Arguments seen: %s\n\n", strings.Join(as, ", "))
			}
			w("```\n%s\n```\n\n", g.errText)
		}
		// Collect-level errors, verbatim, per server.
		w("### Collect() errors (verbatim)\n\n| Server | Collector | Error |\n|---|---|---|\n")
		for _, s := range rep.Servers {
			for _, c := range s.Collectors {
				if c.Error != "" {
					w("| %s | `%s` | `%s` |\n", s.Label, rowKey(c), mdEscape(c.Error))
				}
			}
		}
		w("\n")
	}

	// Statement-level detail.
	w("## Statement detail\n\n")
	w("Rows returned by each distinct traced statement, per server. `ERR` = the statement failed;\n")
	w("`—` = not issued on that server (a different gate variant was selected, or the code path was\n")
	w("skipped). Statement text is truncated; full text is in `results.json`.\n\n")
	for _, k := range order {
		var sqls []string
		idx := map[string]int{}
		res := map[string]map[int]string{} // label -> sql index -> cell
		for _, s := range rep.Servers {
			for _, c := range s.Collectors {
				if rowKey(c) != k {
					continue
				}
				res[s.Label] = map[int]string{}
				for _, st := range c.Statements {
					i, ok := idx[st.SQL]
					if !ok {
						i = len(sqls)
						idx[st.SQL] = i
						sqls = append(sqls, st.SQL)
					}
					v := fmt.Sprint(st.Rows)
					if st.Error != "" {
						v = "ERR"
					}
					if prev, dup := res[s.Label][i]; dup {
						v = prev + ", " + v
					}
					res[s.Label][i] = v
				}
			}
		}
		w("<details><summary><code>%s</code> — %d distinct statement(s)</summary>\n\n", k, len(sqls))
		if len(sqls) == 0 {
			w("No SQL issued on any server.\n\n</details>\n\n")
			continue
		}
		w("| # | Statement |")
		for _, s := range rep.Servers {
			w(" %s |", s.Label)
		}
		w("\n|---|---|")
		for range rep.Servers {
			w("---|")
		}
		w("\n")
		for i, q := range sqls {
			w("| %d | `%s` |", i+1, mdEscape(truncate(q, 160)))
			for _, s := range rep.Servers {
				v, ok := res[s.Label][i]
				if !ok {
					v = "—"
				}
				w(" %s |", v)
			}
			w("\n")
		}
		w("\n</details>\n\n")
	}
	return b.String()
}
